"""Writes installer/manifest.h: every file on the disc (path, size, SHA-256) and the disc's own default.xbe, taken
from a known-good disc image (after the Halo 2 recomp's gen_manifest.py).

    python installer/gen_manifest.py <disc image>
    python installer/gen_manifest.py --folder <game_files>      (a clean extraction, e.g. from extract_disc.py)

rbx_import copies exactly these files and checks each one, so the manifest decides what a good install is. Only
sizes and hashes are written: no game data. The folder form skips the bring-up leftovers package_release.py skips.
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

GAME_NAME = 'Robotech: Battlecry'
GAME_RELEASE = 'USA'
EXCLUDE_SUFFIXES = ('.cine_full', '.cine_short')
EXCLUDE_NAMES = {'default_analysis.json'}
EXCLUDE_DIRS = {'.skipped_for_bringup', 'udata', 'tdata', 'cache'}


def sha(stream, size):
    h = hashlib.sha256()
    while size:
        b = stream.read(min(size, 1 << 22))
        if not b:
            sys.exit('short read')
        h.update(b)
        size -= len(b)
    return h.digest()


def from_image(image):
    img = open(image, 'rb')
    base = None
    for off in (0, 0x18300000, 0x0FD90000, 0x02080000):
        img.seek(off + 32 * 2048)
        v = img.read(28)
        if v[:20] == b'MICROSOFT*XBOX*MEDIA':
            base = off
            root_sector, root_size = struct.unpack('<II', v[20:28])
            break
    if base is None:
        sys.exit(f'{image} is not an Xbox disc image')
    found = {}

    def walk(sector, size, prefix):
        if not size:
            return
        img.seek(base + sector * 2048)
        d = img.read(size)
        pending, seen = [0], set()
        while pending:
            pos = pending.pop()
            if pos in seen or pos + 14 > len(d):
                continue
            seen.add(pos)
            if d[pos:pos + 2] == b'\xff\xff':
                if pos:
                    pending.append(pos + (2048 - pos % 2048))
                continue
            left, right, s, z, attr, nl = struct.unpack('<HHIIBB', d[pos:pos + 14])
            name = prefix + d[pos + 14:pos + 14 + nl].decode('ascii')
            if attr & 0x10:
                walk(s, z, name + '/')
            else:
                found[name] = (s, z)
            pending.extend(p * 4 for p in (right, left) if p)

    walk(root_sector, root_size, '')
    entries = []
    for name in sorted(found, key=str.lower):
        s, z = found[name]
        img.seek(base + s * 2048)
        entries.append((name, z, sha(img, z)))
    return entries


def from_folder(folder):
    entries = []
    for p in sorted(folder.rglob('*'), key=lambda p: p.relative_to(folder).as_posix().lower()):
        rel = p.relative_to(folder)
        if not p.is_file() or p.name in EXCLUDE_NAMES or p.name.endswith(EXCLUDE_SUFFIXES):
            continue
        if any(part.lower() in EXCLUDE_DIRS for part in rel.parts[:-1]):
            continue
        with open(p, 'rb') as f:
            entries.append((rel.as_posix(), p.stat().st_size, sha(f, p.stat().st_size)))
    return entries


def c_bytes(b):
    return '{' + ','.join(str(x) for x in b) + '}'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('image', nargs='?', type=Path)
    ap.add_argument('--folder', type=Path)
    a = ap.parse_args()
    if bool(a.image) == bool(a.folder):
        sys.exit('give a disc image or --folder')
    entries = from_image(a.image) if a.image else from_folder(a.folder)
    xbe = [e for e in entries if e[0].lower() == 'default.xbe']
    if not xbe:
        sys.exit('no default.xbe')
    out = ['/* generated by gen_manifest.py; do not edit. Sizes and SHA-256 only: no game data. */',
           f'#define GAME_NAME "{GAME_NAME}"',
           f'#define GAME_RELEASE "{GAME_RELEASE}"',
           '/* the disc\'s own default.xbe: the release this build was made from */',
           f'static const unsigned char DISC_XBE_SHA256[32] = {c_bytes(xbe[0][2])};',
           f'#define DISC_XBE_SIZE {xbe[0][1]}ULL',
           'static const struct { const char *path; unsigned long long size; unsigned char sha256[32]; } MANIFEST[] = {']
    out += [f'    {{ "{r}", {s}ULL, {c_bytes(d)} }},' for r, s, d in entries]
    out += ['};',
            f'#define MANIFEST_COUNT {len(entries)}',
            f'#define MANIFEST_BYTES {sum(s for _, s, _ in entries)}ULL',
            '']
    Path(__file__).with_name('manifest.h').write_text('\n'.join(out), encoding='utf-8')
    print(len(entries), 'files', sum(s for _, s, _ in entries), 'bytes; default.xbe', xbe[0][2].hex())
    if xbe[0][2].hex() != '2fc8745a72d495626307d644e80f36ec48e216e0132c3c0394446f51f94400b3':
        print('WARNING: this default.xbe is not the one src/main.c was recompiled from')


if __name__ == '__main__':
    main()
