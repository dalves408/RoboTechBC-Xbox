"""Embed third_party/smaa/SMAA.hlsl into src/rbx_smaa_hlsl.h for the D3D11 back end.

Comments and blank lines are dropped so the string stays under MSVC's 64 KB limit for a concatenated
literal; the code itself is unchanged. Run it again after updating SMAA.hlsl:

    python scripts/smaa_hlsl2h.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "smaa" / "SMAA.hlsl"
DST = ROOT / "src" / "rbx_smaa_hlsl.h"


def strip(text: str) -> list:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    lines = []
    for line in text.splitlines():
        line = re.sub(r"//.*$", "", line).rstrip()
        if line.strip():
            lines.append(line)
    return lines


def main() -> None:
    lines = strip(SRC.read_text(encoding="latin-1"))
    out = [
        "/* Generated by scripts/smaa_hlsl2h.py from third_party/smaa/SMAA.hlsl (SMAA 2.8, MIT licence, see",
        " * third_party/smaa/LICENSE.txt). Do not edit; run the script again instead. */",
        "static const char k_hlsl_smaa[] =",
    ]
    for line in lines:
        out.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    out[-1] += ";"
    body = "\n".join(lines)
    if len(body) > 60000:
        raise SystemExit(f"SMAA source is {len(body)} bytes: too long for one MSVC string literal")
    DST.write_text("\n".join(out) + "\n", encoding="ascii", newline="\n")
    print(f"{DST.relative_to(ROOT)}: {len(lines)} lines, {len(body)} bytes")


if __name__ == "__main__":
    main()
